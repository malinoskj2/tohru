local create = dofile("shell/assistant/voice-return.luau")
local gate = create()
gate.begin("voice-chat", "request-1")
assert(gate.take("voice-chat", "request-1", "final-1", true, false))
assert(not gate.take("voice-chat", "request-1", "final-1", true, false))
assert(not gate.take("other-chat", "request-1", "foreign", true, false))
assert(not gate.take("voice-chat", "request-1", "hidden", false, false))
assert(not gate.take("voice-chat", "request-1", "hidden", true, false))
assert(not gate.take("voice-chat", "request-1", "busy", true, true))
gate.begin("voice-chat", "request-2")
assert(not gate.take("voice-chat", "request-1", "old-request", true, false))
assert(gate.take("voice-chat", "request-2", "current", true, false))
gate.interrupt()
assert(not gate.take("voice-chat", "request-2", "interrupted", true, false))
gate.begin("text-chat", "")
assert(not gate.take("text-chat", "", "text-origin", true, false))
print("voice continuation delivery cases passed")
