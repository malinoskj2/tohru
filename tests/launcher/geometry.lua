local grid = assert(loadfile("shell/launcher/geometry.luau"))()
-- One pin then applications: Down moves to first app directly below, not +8.
assert(grid.neighbour(8, 1, 0, 20, 1) == 1)
assert(grid.neighbour(8, 1, 1, 20, -1) == 0)
assert(grid.neighbour(8, 3, 2, 20, 1) == 5)
assert(grid.neighbour(8, 3, 5, 20, -1) == 2)
assert(grid.neighbour(8, 0, 17, 20, 1) == 17)
assert(grid.neighbour(8, 0, 7, 10, 1) == 9)
assert(grid.neighbour(7, 7, 3, 24, 1) == 10)
-- Rows of 82 px under a 26 px heading; Home's applications under a second heading.
local x, y = grid.position(7, 0, 0)
assert(x == 0 and y == 26)
x, y = grid.position(7, 0, 8)
assert(x == 1 and y == 108)
x, y = grid.position(7, 7, 6)
assert(x == 6 and y == 26)
x, y = grid.position(7, 7, 7)
assert(x == 0 and y == 134)
x, y = grid.position(7, 7, 14)
assert(x == 0 and y == 216)
assert(grid.content(8, 1, 1) == 142)
assert(grid.content(8, 0, 9) == 198)
assert(grid.content(7, 0, 0) == 0)
assert(grid.follow(8, 1, 0, 200, 432) == 0)
assert(grid.follow(8, 1, 17, 0, 200) == 184)
assert(grid.follow(7, 0, 0, 0, 440) == 0)
print("Launcher rows, section headings and follow fixtures passed")
